"""Write content/printed-text.json: the text printed on each published card's pinned printing (issue #1358).

The sidebar shows a selected card's engine text only when it differs from what the scan shows (an erratum, a correction, a reading the engine
spells out), so the client needs the printed text to compare with. The printing is the one whose scan the card uses (the image named in a
*-sources.json), else the catalogue's primary printing. Oracle records a printing's own text only where it differs from the current text
(text_override), so a printing without one reads the current Oracle text. The comparison itself (symbols, punctuation, case) is in Core
(PrintedText.cs), against the engine text at run time, so a later engine correction shows up without regenerating this file.

    python3 tools/content/printed_text.py           # rewrite the file
    python3 tools/content/printed_text.py --check   # fail when a recorded text is wrong (a newly wired card may be missing: its text is shown)
"""
import glob
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "content/printed-text.json"
CATALOGUES = ["content/oracle/emperor-catalogue.json", "content/oracle/emperor-supplemental-catalogue.json"]


def build() -> dict:
    oracle = {}
    for rel in CATALOGUES:
        for card in json.loads((ROOT / rel).read_text(encoding="utf-8"))["cards"]:
            oracle[card["id"]] = card
    scan_printing = {}
    for path in sorted(glob.glob(str(ROOT / "content/published/*-sources.json"))):
        for source in json.loads(Path(path).read_text(encoding="utf-8")):
            match = re.search(r"-printing-(\d+)-image", source.get("image_path") or "")
            if match:
                scan_printing.setdefault(source["card_id"], match.group(1))
    published = set()
    for path in glob.glob(str(ROOT / "content/published/*.json")):
        if path.endswith("-sources.json"):
            continue
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        if isinstance(data, dict) and isinstance(data.get("Cards"), list):
            published.update(card["Id"] for card in data["Cards"])
    texts = {}
    for card_id in sorted(published):
        card = oracle.get(card_id)
        if card is None:
            continue  # no Oracle record (a created proxy, a training card): the sidebar keeps showing its text
        printing_id = scan_printing.get(card_id) or card.get("current_primary_printing_id")
        printing = next((p for p in card.get("printings") or [] if p.get("id") == printing_id), {})
        text = printing.get("text_override") or card.get("current_oracle_text") or ""
        texts[card_id] = text
    return {"notice": "Generated by tools/content/printed_text.py from the Oracle catalogues: the text on each published card's pinned printing (issue #1358).",
            "cards": texts}


def render(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    data = build()
    if "--check" in sys.argv:
        # Every recorded text must still be the printing's; a card wired since the last run is simply absent, and the sidebar shows its text until the file is rewritten.
        recorded = json.loads(OUT.read_text(encoding="utf-8"))["cards"] if OUT.exists() else {}
        wrong = sorted(card_id for card_id, text in recorded.items() if data["cards"].get(card_id) != text)
        if wrong:
            print(f"{OUT.relative_to(ROOT)} disagrees with the catalogues for {len(wrong)} cards ({', '.join(wrong[:5])}): run python3 tools/content/printed_text.py")
            return 1
        return 0
    text = render(data)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
