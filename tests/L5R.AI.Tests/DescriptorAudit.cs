using System.Text;
using System.Text.Json;
using L5R.AI;
using L5R.Core;

// Issue #1206 (docs/bots/CONAN_STRATEGY_BRIEF.md step 2): the coverage audit of the effect descriptors. Every ability of every card in the tournament decks and in the decks of Mendon's replays
// is classified or listed as unknown, per deck, and a fixed random sample of 60 is printed with its label for a hand check against the card text. Opt-in:
//   L5R_DESC_OUT=<path.md>   writes the audit (default docs/bots/strategy/descriptors/coverage.md); L5R_DESC_SAMPLE=<n> the sample size (60); L5R_DESC_SEED=<n> its seed (1206)
//   dotnet run -c Release --project tests/L5R.AI.Tests -- --filter descriptor-audit
internal static class DescriptorAudit
{
    public static readonly (string, Action)[] Tests =
    [
        ("descriptor-audit: every ability in the tournament and replay decks classified or listed unknown, with a sample for the hand check (opt-in, set L5R_DESC_OUT)", () =>
        {
            if (Environment.GetEnvironmentVariable("L5R_DESC_OUT") is not { Length: > 0 } outPath) { Console.WriteLine("  SKIP: set L5R_DESC_OUT"); return; }
            Console.WriteLine(Run(outPath, int.TryParse(Environment.GetEnvironmentVariable("L5R_DESC_SAMPLE"), out var n) ? n : 60, int.TryParse(Environment.GetEnvironmentVariable("L5R_DESC_SEED"), out var s) ? s : 1206));
        })
    ];

    private static IEnumerable<(string Deck, Deck Cards)> Decks()
    {
        var pool = DeckArchetypeTests.PoolDecks(Environment.GetEnvironmentVariable("L5R_TOURN_DECKS") ?? "src/L5R.Client/Content/preloaded-decks.json");
        foreach (var (name, deck) in pool) yield return (name, deck);
        yield return ("Lion preset", CustomPractice.Preset("Lion")); yield return ("Crane preset", CustomPractice.Preset("Crane"));
        var web = new JsonSerializerOptions(JsonSerializerDefaults.Web);
        foreach (var path in Directory.GetFiles(Path.Combine("docs", "bots", "replays"), "*.json").Order())
        {
            var replay = JsonSerializer.Deserialize<ReplayRecord>(File.ReadAllText(path), web);
            if (replay?.CustomDecks is { Length: 2 } decks) for (var i = 0; i < 2; i++) yield return ($"{Path.GetFileNameWithoutExtension(path)} seat {i}", decks[i]);
        }
    }

    public static string Run(string outPath, int sampleSize, int seed)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Effect descriptor coverage (issue #1206, step 2)\n");
        sb.AppendLine($"Generated by `--filter descriptor-audit` on {DateTime.UtcNow:yyyy-MM-dd}: every ability of every card in the tournament pool decks and the replay decks, read by `EffectDescriptors.Of`. Unknown = no clause matched.\n");
        var all = new Dictionary<string, (string Card, AbilityDefinition Ability)>(StringComparer.Ordinal);
        var perDeck = new List<(string Deck, int Abilities, int Unknown, int Battle, int BattleUnknown, string[] UnknownIds)>();
        foreach (var (deckName, deck) in Decks())
        {
            var ids = new List<(string Card, string Id)>();
            foreach (var entry in deck.Entries)
            {
                var def = CardCatalog.Cards.Values.Where(c => c.Name == entry.Name).OrderBy(c => c.ScenarioOnly).FirstOrDefault();
                foreach (var id in def?.Abilities ?? []) if (AbilityCatalog.All.TryGetValue(id, out var ab)) { ids.Add((def!.Name, id)); all.TryAdd(id, (def.Name, ab)); }
            }
            var distinct = ids.DistinctBy(x => x.Id).ToArray();
            var unknown = distinct.Where(x => EffectDescriptors.Of(x.Id).Class == EffectClass.Unknown).ToArray();
            var battle = distinct.Where(x => EffectDescriptors.Of(x.Id).IsBattle).ToArray();
            perDeck.Add((deckName, distinct.Length, unknown.Length, battle.Length, battle.Count(x => EffectDescriptors.Of(x.Id).Class == EffectClass.Unknown), unknown.Select(x => x.Id).ToArray()));
        }
        sb.AppendLine("## By deck\n\n| deck | abilities | unknown | Battle abilities | Battle unknown | unknown ids |\n|---|---|---|---|---|---|");
        foreach (var d in perDeck) sb.AppendLine($"| {d.Deck} | {d.Abilities} | {d.Unknown} ({(d.Abilities == 0 ? 0 : 100 * d.Unknown / d.Abilities)}%) | {d.Battle} | {d.BattleUnknown} | {string.Join(", ", d.UnknownIds)} |");
        var classes = all.Keys.Select(EffectDescriptors.Of).GroupBy(d => d.Class).OrderByDescending(g => g.Count());
        sb.AppendLine($"\n## By class ({all.Count} distinct abilities)\n\n| class | abilities |\n|---|---|");
        foreach (var g in classes) sb.AppendLine($"| {g.Key} | {g.Count()} |");
        var rng = new Random(seed); var sample = all.Keys.Order(StringComparer.Ordinal).OrderBy(_ => rng.Next()).Take(sampleSize).Order(StringComparer.Ordinal).ToArray();
        sb.AppendLine($"\n## Hand-check sample ({sample.Length}, seed {seed})\n\nVerdict column to be filled by the reader: right / wrong / unclear.\n\n| # | ability | card | timing | label | descriptor | verdict |\n|---|---|---|---|---|---|---|");
        var n = 0;
        foreach (var id in sample) { var (card, ab) = all[id]; sb.AppendLine($"| {++n} | `{id}` | {card} | {ab.Timing} [{ab.Target}] | {Escape(ab.Label)} | {Escape(EffectDescriptors.Of(id).ToString())} | |"); }
        sb.AppendLine("\n## Every ability\n\n| ability | card | timing | label | descriptor |\n|---|---|---|---|---|");
        foreach (var id in all.Keys.Order(StringComparer.Ordinal)) { var (card, ab) = all[id]; sb.AppendLine($"| `{id}` | {card} | {ab.Timing} [{ab.Target}] | {Escape(ab.Label)} | {Escape(EffectDescriptors.Of(id).ToString())} |"); }
        var dir = Path.GetDirectoryName(Path.GetFullPath(outPath)); if (dir is not null) Directory.CreateDirectory(dir);
        File.WriteAllText(outPath, sb.ToString());
        return $"  wrote {outPath}: {all.Count} abilities over {perDeck.Count} decks, unknown {all.Keys.Count(id => EffectDescriptors.Of(id).Class == EffectClass.Unknown)}";
    }

    private static string Escape(string? s) => (s ?? "").Replace("|", "\\|").Replace("\n", " ");
}
